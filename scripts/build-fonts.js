const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.resolve(__dirname, "..");
const manifestPath = path.join(root, "assets/fonts/font-manifest.json");
const cssPath = path.join(root, "versions/src/css/00-fonts.css");
const sha256 = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");

function parseRanges(value) {
  const points = new Set();
  for (const range of value.split(/,\s*/)) {
    const match = /^U\+([0-9A-F]+)(?:-([0-9A-F]+))?$/.exec(range);
    if (!match) throw new Error(`Invalid font Unicode range: ${range}`);
    const first = Number.parseInt(match[1], 16);
    const last = Number.parseInt(match[2] || match[1], 16);
    if (first > last || last > 0x10ffff) throw new Error(`Invalid font Unicode bounds: ${range}`);
    for (let code = first; code <= last; code += 1) points.add(code);
  }
  return points;
}

function pointHash(points) {
  return sha256([...points].sort((a, b) => a - b).map((code) => code.toString(16).toUpperCase()).join(","));
}

function verifyAsset(asset) {
  if (!asset.path.startsWith("assets/fonts/") || asset.path.includes("..")) throw new Error("Font asset path escapes assets/fonts");
  const bytes = fs.readFileSync(path.join(root, asset.path));
  if (bytes.length !== asset.bytes || sha256(bytes) !== asset.sha256) throw new Error(`${asset.path} differs from the verified font manifest`);
}

function fontFace(manifest, asset, comment) {
  return `/* ${comment} */\n@font-face {\n  font-family: "${manifest.family}";\n  font-style: normal;\n  font-weight: ${manifest.cssWeight.join(" ")};\n  font-display: ${manifest.display};\n  src: url("../${asset.path}") format("woff2-variations");\n  unicode-range: ${asset.unicodeRange};\n}\n`;
}

function render(manifest) {
  let css = `/* Generated by scripts/build-fonts.js. Do not edit by hand.\n * Unmodified Pretendard ${manifest.upstream.release} official variable subsets.\n * Copyright (c) 2021 Kil Hyung-jin; Reserved Font Name Pretendard.\n * SIL Open Font License: assets/fonts/PRETENDARD-OFL.txt.\n */\n\n`;
  // Keep the complete original available only for codepoints not shipped in the
  // official dynamic subsets. This preserves future content's character support.
  css += fontFace(manifest, manifest.fallback, "Original font for the remaining supported characters") + "\n";
  manifest.subsets.forEach((asset, index) => {
    css += fontFace(manifest, asset, `Official subset ${index}`) + "\n";
  });
  return css.trimEnd() + "\n";
}

function verify(manifest) {
  if (manifest.version !== 1 || manifest.family !== "Studio Pretendard" || manifest.display !== "block" ||
      JSON.stringify(manifest.cssWeight) !== "[45,920]") throw new Error("Unexpected font rendering configuration");
  [manifest.source, manifest.license, manifest.upstream.css, ...manifest.subsets].forEach(verifyAsset);
  const source = parseRanges(manifest.source.unicodeRange);
  if (source.size !== manifest.source.codepointCount || pointHash(source) !== manifest.source.codepointsHash) {
    throw new Error("Original font character manifest is inconsistent");
  }
  const covered = new Set();
  for (const subset of manifest.subsets) {
    if (JSON.stringify(subset.axes) !== JSON.stringify(manifest.source.axes)) throw new Error(`${subset.path} has different variable axes`);
    const points = parseRanges(subset.unicodeRange);
    if (points.size !== subset.codepointCount || pointHash(points) !== subset.codepointsHash) throw new Error(`${subset.path} has invalid character coverage`);
    for (const point of points) {
      if (!source.has(point) || covered.has(point)) throw new Error(`${subset.path} has missing or overlapping character coverage`);
      covered.add(point);
    }
  }
  if (manifest.fallback.path !== manifest.source.path) throw new Error("Remaining characters must use the preserved original font");
  const remainder = parseRanges(manifest.fallback.unicodeRange);
  if (remainder.size !== manifest.fallback.codepointCount || pointHash(remainder) !== manifest.fallback.codepointsHash) throw new Error("Original-font remainder is inconsistent");
  for (const point of remainder) {
    if (!source.has(point) || covered.has(point)) throw new Error("Original-font remainder overlaps subsets or adds unsupported characters");
    covered.add(point);
  }
  if (covered.size !== source.size) throw new Error("Font splitting lost supported characters");
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  verify(manifest);
  const css = render(manifest);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(cssPath) || fs.readFileSync(cssPath, "utf8") !== css) throw new Error("Generated font CSS is stale; run npm run build:fonts");
    console.log(`Fonts checked: ${manifest.subsets.length} unchanged official subsets; all ${manifest.source.codepointCount} original characters and variable axes preserved.`);
  } else {
    fs.writeFileSync(cssPath, css);
    console.log(`Generated ${path.relative(root, cssPath)} for ${manifest.subsets.length} official subsets and the preserved original remainder.`);
  }
}

if (require.main === module) {
  try { main(); } catch (error) {
    console.error(`Font ${process.argv.includes("--check") ? "check" : "build"} failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { render, verify };
